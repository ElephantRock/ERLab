#!/usr/bin/env python3
"""Tabular Robust Regression v1 — Frozen Entrypoint.

Capability: tabular_robust_regression_v1
Protocol: ridge and Huber regression vs mean-predictor baseline on
          standardized tabular features, evaluated under seeded
          deterministic covariate perturbation severities with
          MAE / RMSE / R2 metrics.

This is a checked-in, reviewed analysis entrypoint. It is NOT
generated by an LLM. It receives:
  --input  : path to a registered regression dataset file
             (whitespace/tab/comma-delimited numeric rows; the last
             column is the continuous target; no header expected, but
             a non-numeric first row is treated as a header)
  --output : directory for result artifacts

It writes:
  metrics.json          — flat authoritative metrics for the manifest
  condition_metrics.json — detailed per-condition breakdown

Exit codes:
  0 = success
  1 = runtime error
  2 = invalid results (non-finite or missing)
"""

from __future__ import annotations

import csv
import json
import math
import os
import random
import sys
from pathlib import Path

# ── Fixed protocol constants (frozen; mirror the C3-0 manifest) ─────────────

SEED = 42
TRAIN_FRACTION = 0.8
RIDGE_LAMBDA = 1.0
HUBER_DELTA_FACTOR = 1.345
MAD_TO_SIGMA = 1.4826
IRLS_MAX_ITER = 50

PERTURB_SEVERITIES = [0.0, 0.25, 0.5, 0.75]
PERTURB_STD_FACTOR = 0.5  # noise std = severity * 0.5 (standardized space)

METHODS = ["ridge", "huber"]


# ── Data loading ────────────────────────────────────────────────────────────


def _parse_float(tok: str) -> float | None:
    try:
        return float(tok)
    except ValueError:
        return None


def load_dataset(path: str):
    """Load a numeric regression file. Returns (rows, target).

    Rows are lists of float features; target is a float. The last
    column is the target. A first row whose fields are not all numeric
    is treated as a header. Rows containing non-numeric fields beyond
    that are skipped.
    """
    with open(path, newline="") as f:
        raw_lines = [ln for ln in f.read().splitlines() if ln.strip()]
    parsed_rows: list[list[float]] = []
    for ln in raw_lines:
        # Tolerate tab, comma, multi-space, and semicolon delimiters.
        for delim in ("\t", ";", ","):
            if delim in ln:
                tokens = [t for t in ln.split(delim) if t.strip() != ""]
                break
        else:
            tokens = ln.split()
        vals = [_parse_float(t) for t in tokens]
        if all(v is not None for v in vals) and len(vals) >= 2:
            parsed_rows.append([float(v) for v in vals])  # type: ignore[arg-type]
    if not parsed_rows:
        print("ERROR: no numeric rows parsed", file=sys.stderr)
        sys.exit(1)
    # Header detection: if the FIRST line failed numeric parsing but
    # later lines succeeded, the first line was a header and was
    # already excluded by the numeric filter above.
    features = [r[:-1] for r in parsed_rows]
    target = [r[-1] for r in parsed_rows]
    return features, target


# ── Deterministic split & standardization ───────────────────────────────────


def split_train_test(n: int, seed: int = SEED):
    """Seeded shuffle split: first 80% train, last 20% test."""
    rng = random.Random(seed)
    idx = list(range(n))
    rng.shuffle(idx)
    n_train = int(n * TRAIN_FRACTION)
    return idx[:n_train], idx[n_train:]


def fit_standardizer(X):
    """Per-feature mean/std from the TRAINING matrix."""
    n, d = len(X), len(X[0])
    means = [sum(row[j] for row in X) / n for j in range(d)]
    stds = []
    for j in range(d):
        var = sum((row[j] - means[j]) ** 2 for row in X) / n
        stds.append(math.sqrt(var) if var > 0 else 1.0)
    return means, stds


def standardize(X, means, stds):
    return [
        [(row[j] - means[j]) / stds[j] for j in range(len(means))]
        for row in X
    ]


# ── Linear algebra (pure Python) ────────────────────────────────────────────


def mat_vec(A, x):
    return [sum(A[i][j] * x[j] for j in range(len(x))) for i in range(len(A))]


def solve_linear(M, b):
    """Solve Mx = b by Gaussian elimination with partial pivoting."""
    n = len(M)
    A = [row[:] + [b[i]] for i, row in enumerate(M)]
    for col in range(n):
        piv = max(range(col, n), key=lambda r: abs(A[r][col]))
        if abs(A[piv][col]) < 1e-14:
            raise ValueError("singular matrix")
        A[col], A[piv] = A[piv], A[col]
        for r in range(col + 1, n):
            factor = A[r][col] / A[col][col]
            for c in range(col, n + 1):
                A[r][c] -= factor * A[col][c]
    x = [0.0] * n
    for i in range(n - 1, -1, -1):
        s = A[i][n] - sum(A[i][j] * x[j] for j in range(i + 1, n))
        x[i] = s / A[i][i]
    return x


def _design(X_std):
    """Standardized features plus an unregularized bias column."""
    return [row + [1.0] for row in X_std]


def fit_ridge(X_std, y, lam: float = RIDGE_LAMBDA):
    """Closed-form ridge with the bias column unregularized."""
    Xd = _design(X_std)
    n, d = len(Xd), len(Xd[0])
    XtX = [
        [sum(Xd[k][i] * Xd[k][j] for k in range(n)) for j in range(d)]
        for i in range(d)
    ]
    Xty = [sum(Xd[k][i] * y[k] for k in range(n)) for i in range(d)]
    for i in range(d - 1):  # regularize every column except the bias
        XtX[i][i] += lam
    return solve_linear(XtX, Xty)


def predict_linear(w, X_std):
    Xd = _design(X_std)
    return [sum(w[j] * row[j] for j in range(len(w))) for row in Xd]


def fit_huber(X_std, y, ridge_w):
    """Huber regression via IRLS, initialized from the ridge solution.

    Residual scale sigma = MAD_TO_SIGMA * MAD of the current
    residuals, where MAD is the median absolute deviation about the
    residual median (floored at 1e-8); delta = HUBER_DELTA_FACTOR *
    sigma; weight w_i = min(1, delta/|r_i|); each iteration refits
    weighted ridge with the same RIDGE_LAMBDA (bias unregularized).
    Exactly IRLS_MAX_ITER iterations run, per the pre-registered
    protocol.
    """
    # Exactly IRLS_MAX_ITER iterations, per the pre-registered
    # protocol ("fixed 50 iterations"). Converged iterates are
    # numerical no-ops, so no early stopping.
    w = list(ridge_w)
    Xd = _design(X_std)
    n, d = len(Xd), len(Xd[0])
    for _ in range(IRLS_MAX_ITER):
        resid = [y[i] - sum(w[j] * Xd[i][j] for j in range(d)) for i in range(n)]
        # MAD about the residual median: median(|r - median(r)|).
        resid_sorted = sorted(resid)
        resid_median = (
            resid_sorted[n // 2]
            if n % 2 == 1
            else 0.5
            * (resid_sorted[n // 2 - 1] + resid_sorted[n // 2])
        )
        deviations = sorted(abs(r - resid_median) for r in resid)
        m = len(deviations)
        mad = (
            deviations[m // 2]
            if m % 2 == 1
            else 0.5 * (deviations[m // 2 - 1] + deviations[m // 2])
        )
        sigma = max(MAD_TO_SIGMA * mad, 1e-8)
        delta = HUBER_DELTA_FACTOR * sigma
        weights = [1.0 if abs(r) <= delta else delta / abs(r) for r in resid]
        XtX = [
            [
                sum(weights[k] * Xd[k][i] * Xd[k][j] for k in range(n))
                for j in range(d)
            ]
            for i in range(d)
        ]
        Xty = [sum(weights[k] * Xd[k][i] * y[k] for k in range(n)) for i in range(d)]
        for i in range(d - 1):
            XtX[i][i] += RIDGE_LAMBDA
        w = solve_linear(XtX, Xty)
    return w


# ── Seeded covariate perturbation ───────────────────────────────────────────


def _gaussian_pair(rng: random.Random):
    """Box-Muller standard normal."""
    u1 = max(rng.random(), 1e-12)
    u2 = rng.random()
    r = math.sqrt(-2.0 * math.log(u1))
    return r * math.cos(2 * math.pi * u2), r * math.sin(2 * math.pi * u2)


def perturb_test_set(X_std, severity_index: int, severity: float):
    """Zero-mean Gaussian noise on standardized TEST features only.

    std = severity * PERTURB_STD_FACTOR; deterministic per severity
    (seed SEED + severity_index); labels untouched.
    """
    if severity <= 0.0:
        return [row[:] for row in X_std]
    rng = random.Random(SEED + severity_index)
    std = severity * PERTURB_STD_FACTOR
    out = []
    for row in X_std:
        noisy = []
        for j in range(len(row)):
            z, _ = _gaussian_pair(rng)
            noisy.append(row[j] + std * z)
        out.append(noisy)
    return out


# ── Metrics ─────────────────────────────────────────────────────────────────


def mae(y_true, y_pred):
    n = len(y_true)
    return sum(abs(a - b) for a, b in zip(y_true, y_pred)) / n


def rmse(y_true, y_pred):
    n = len(y_true)
    return math.sqrt(sum((a - b) ** 2 for a, b in zip(y_true, y_pred)) / n)


def r2_score(y_true, y_pred):
    mean = sum(y_true) / len(y_true)
    ss_tot = sum((a - mean) ** 2 for a in y_true)
    ss_res = sum((a - b) ** 2 for a, b in zip(y_true, y_pred))
    if ss_tot <= 0:
        return 0.0
    return 1.0 - ss_res / ss_tot


# ── Main ────────────────────────────────────────────────────────────────────


def main():
    import argparse

    parser = argparse.ArgumentParser(
        description="Tabular robust regression v1 (frozen entrypoint)",
    )
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    os.makedirs(args.output, exist_ok=True)

    X, y = load_dataset(args.input)
    if len(X) < 10:
        print(f"ERROR: too few rows ({len(X)})", file=sys.stderr)
        sys.exit(1)
    n_features = len(X[0])
    if any(len(r) != n_features for r in X):
        print("ERROR: inconsistent feature count", file=sys.stderr)
        sys.exit(1)

    train_idx, test_idx = split_train_test(len(X))
    X_train = [X[i] for i in train_idx]
    y_train = [y[i] for i in train_idx]
    X_test = [X[i] for i in test_idx]
    y_test = [y[i] for i in test_idx]

    means, stds = fit_standardizer(X_train)
    Xtr = standardize(X_train, means, stds)
    Xte = standardize(X_test, means, stds)

    # Baseline: training-set mean predictor (severity-independent —
    # its predictions do not read the covariates).
    train_mean = sum(y_train) / len(y_train)
    baseline_pred = [train_mean] * len(y_test)

    # Fitted models.
    ridge_w = fit_ridge(Xtr, y_train)
    huber_w = fit_huber(Xtr, y_train, ridge_w)

    flat_metrics: dict[str, float] = {}
    conditions = []

    for m_name, m_w in (("ridge", ridge_w), ("huber", huber_w)):
        for sev_i, sev in enumerate(PERTURB_SEVERITIES):
            Xte_p = perturb_test_set(Xte, sev_i, sev)
            pred = predict_linear(m_w, Xte_p)
            m_mae = mae(y_test, pred)
            m_rmse = rmse(y_test, pred)
            m_r2 = r2_score(y_test, pred)
            sev_label = str(sev).replace(".", "_")
            flat_metrics[f"{sev_label}_{m_name}_mae"] = round(m_mae, 6)
            flat_metrics[f"{sev_label}_{m_name}_rmse"] = round(m_rmse, 6)
            flat_metrics[f"{sev_label}_{m_name}_r2"] = round(m_r2, 6)
            conditions.append({
                "dataset": Path(args.input).stem,
                "perturbation_severity": sev,
                "method": m_name,
                "n_test": len(y_test),
                "mae": round(m_mae, 6),
                "rmse": round(m_rmse, 6),
                "r2": round(m_r2, 6),
            })

    flat_metrics["baseline_mae"] = round(mae(y_test, baseline_pred), 6)
    flat_metrics["baseline_rmse"] = round(rmse(y_test, baseline_pred), 6)
    flat_metrics["baseline_r2"] = round(r2_score(y_test, baseline_pred), 6)

    for name, val in flat_metrics.items():
        if not isinstance(val, (int, float)) or not math.isfinite(val):
            print(f"ERROR: metric {name} not finite: {val}", file=sys.stderr)
            sys.exit(2)

    metrics = {
        "schema_version": "2",
        "experiment_spec_id": "tabular-robust-regression-v1",
        "seed": SEED,
        "sample_counts": {
            "train": len(train_idx),
            "test": len(test_idx),
        },
        "perturbation_severities": PERTURB_SEVERITIES,
        "methods": METHODS,
        "protocol_constants": {
            "ridge_lambda": RIDGE_LAMBDA,
            "huber_delta_factor": HUBER_DELTA_FACTOR,
            "mad_to_sigma": MAD_TO_SIGMA,
            "irls_max_iter": IRLS_MAX_ITER,
            "perturb_std_factor": PERTURB_STD_FACTOR,
        },
        "metrics": flat_metrics,
    }
    with open(os.path.join(args.output, "metrics.json"), "w") as f:
        json.dump(metrics, f, indent=2)
    with open(os.path.join(args.output, "condition_metrics.json"), "w") as f:
        json.dump(conditions, f, indent=2)

    print(f"Analysis complete. baseline_mae={flat_metrics['baseline_mae']:.4f}")
    print(f"Conditions: {len(conditions)}")
    print(f"Metrics: {len(flat_metrics)} flat values")
    sys.exit(0)


if __name__ == "__main__":
    main()
