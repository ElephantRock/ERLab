#!/usr/bin/env python3
"""Phase 5 Pilot — Frozen Analysis Entrypoint.

Spec: phase5-pilot-v1
Dataset: Iris (150 rows, 4 features, 3 species)
Method: One-vs-rest logistic regression via gradient descent vs majority-class baseline
Split: Stratified by species, 80/20, seed=42

This script is the checked-in, reviewed analysis entrypoint for the Phase 5
empirical pilot. It is NOT generated by the LLM. It receives:
  --input  : path to iris_raw.csv
  --output : directory for result artifacts

It writes:
  metrics.json      — strict schema, the authoritative result store
  predictions.csv   — per-sample predictions from both baselines
  results_table.csv — summary table for paper inclusion

Exit codes:
  0 = success (all artifacts written, metrics valid)
  1 = runtime error
  2 = invalid results (metrics missing or non-finite)
"""

import csv
import hashlib
import json
import math
import os
import sys


def load_iris(path):
    """Load the frozen Iris CSV. Returns list of (features, label) tuples."""
    rows = []
    with open(path, newline="") as f:
        reader = csv.reader(f)
        for row in reader:
            if len(row) != 5:
                continue
            features = [float(row[0]), float(row[1]), float(row[2]), float(row[3])]
            label = row[4]
            rows.append((features, label))
    return rows


def stratified_split(rows, train_fraction=0.8, seed=42):
    """Fixed stratified split: shuffle within each species, take first 80%."""
    import random
    rng = random.Random(seed)
    by_species = {}
    for features, label in rows:
        by_species.setdefault(label, []).append(features)

    train, test = [], []
    for species in sorted(by_species.keys()):
        samples = by_species[species][:]
        rng.shuffle(samples)
        n_train = int(len(samples) * train_fraction)
        train.extend([(s, species) for s in samples[:n_train]])
        test.extend([(s, species) for s in samples[n_train:]])

    # Shuffle the combined sets for good measure (deterministic)
    rng2 = random.Random(seed + 1)
    rng2.shuffle(train)
    rng2.shuffle(test)
    return train, test


def sigmoid(z):
    if z >= 0:
        ez = math.exp(-z)
        return 1.0 / (1.0 + ez)
    else:
        ez = math.exp(z)
        return ez / (1.0 + ez)


def train_logistic_regression(train_X, train_y, lr=0.01, epochs=500, l2=0.01):
    """One-vs-rest logistic regression via gradient descent.
    Returns a dict: class_name -> (weights, bias)."""
    classes = sorted(set(train_y))
    models = {}
    n_features = len(train_X[0])
    n_samples = len(train_X)

    for cls in classes:
        binary_y = [1 if y == cls else 0 for y in train_y]
        weights = [0.0] * n_features
        bias = 0.0

        for epoch in range(epochs):
            grad_w = [0.0] * n_features
            grad_b = 0.0
            for i in range(n_samples):
                z = bias + sum(weights[j] * train_X[i][j] for j in range(n_features))
                pred = sigmoid(z)
                error = pred - binary_y[i]
                for j in range(n_features):
                    grad_w[j] += error * train_X[i][j]
                grad_b += error

            for j in range(n_features):
                grad_w[j] = grad_w[j] / n_samples + l2 * weights[j]
                weights[j] -= lr * grad_w[j]
            bias -= lr * grad_b / n_samples

        models[cls] = (weights, bias)
    return models


def predict_multinomial(models, features):
    """Predict the class with highest one-vs-rest probability."""
    best_cls = None
    best_score = -1.0
    for cls, (weights, bias) in models.items():
        z = bias + sum(weights[j] * features[j] for j in range(len(features)))
        score = sigmoid(z)
        if score > best_score:
            best_score = score
            best_cls = cls
    return best_cls


def majority_class(labels):
    """Return the most frequent label."""
    counts = {}
    for l in labels:
        counts[l] = counts.get(l, 0) + 1
    return max(counts, key=counts.get)


def accuracy(y_true, y_pred):
    correct = sum(1 for t, p in zip(y_true, y_pred) if t == p)
    return correct / len(y_true) if y_true else 0.0


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Phase 5 pilot analysis")
    parser.add_argument("--input", required=True, help="Path to iris_raw.csv")
    parser.add_argument("--output", required=True, help="Output directory for artifacts")
    args = parser.parse_args()

    os.makedirs(args.output, exist_ok=True)

    # Load and split
    rows = load_iris(args.input)
    if len(rows) != 150:
        print(f"ERROR: expected 150 rows, got {len(rows)}", file=sys.stderr)
        sys.exit(1)

    train, test = stratified_split(rows, train_fraction=0.8, seed=42)
    train_X = [t[0] for t in train]
    train_y = [t[1] for t in train]
    test_X = [t[0] for t in test]
    test_y = [t[1] for t in test]

    # Train logistic regression
    models = train_logistic_regression(train_X, train_y, lr=0.05, epochs=1000, l2=0.001)

    # Majority-class baseline
    majority = majority_class(train_y)
    baseline_preds = [majority] * len(test_y)
    baseline_acc = accuracy(test_y, baseline_preds)

    # Model predictions
    model_preds = [predict_multinomial(models, x) for x in test_X]
    model_acc = accuracy(test_y, model_preds)
    improvement = model_acc - baseline_acc

    # Validate metrics are finite
    for name, val in [("baseline_accuracy", baseline_acc),
                      ("model_accuracy", model_acc),
                      ("improvement", improvement)]:
        if not math.isfinite(val):
            print(f"ERROR: metric {name} is not finite: {val}", file=sys.stderr)
            sys.exit(2)

    # Write metrics.json (authoritative result store)
    metrics = {
        "schema_version": "1",
        "experiment_spec_id": "phase5-pilot-v1",
        "seed": 42,
        "sample_counts": {"train": len(train), "test": len(test)},
        "majority_class": majority,
        "metrics": {
            "baseline_accuracy": round(baseline_acc, 6),
            "model_accuracy": round(model_acc, 6),
            "improvement": round(improvement, 6),
        },
    }
    metrics_path = os.path.join(args.output, "metrics.json")
    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)

    # Write predictions.csv
    pred_path = os.path.join(args.output, "predictions.csv")
    with open(pred_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["sample_idx", "true_label", "baseline_pred", "model_pred"])
        for i, (true, bp, mp) in enumerate(zip(test_y, baseline_preds, model_preds)):
            writer.writerow([i, true, bp, mp])

    # Write results_table.csv (summary for paper)
    table_path = os.path.join(args.output, "results_table.csv")
    with open(table_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["Method", "Test Accuracy", "Train Samples", "Test Samples"])
        writer.writerow([f"Majority Class ({majority})", f"{baseline_acc:.4f}", len(train), len(test)])
        writer.writerow(["Logistic Regression (OvR)", f"{model_acc:.4f}", len(train), len(test)])
        writer.writerow(["Improvement", f"{improvement:+.4f}", "", ""])

    print(f"Analysis complete. baseline_acc={baseline_acc:.4f} model_acc={model_acc:.4f} improvement={improvement:+.4f}")
    print(f"Artifacts written to {args.output}/")
    sys.exit(0)


if __name__ == "__main__":
    main()
