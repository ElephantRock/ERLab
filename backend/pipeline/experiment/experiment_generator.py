"""Experiment code generator — produces Python experiment scripts from research ideas.

BATCH-66/TASK-01: Generates executable experiment code that:
  1. States the hypothesis from the idea's problem statement
  2. Creates a synthetic test dataset
  3. Runs a simple baseline comparison
  4. Measures and prints results as JSON

Uses only standard-library imports (random, statistics, time, json) so that
generated code needs no additional pip packages.
"""

from __future__ import annotations

import textwrap
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from backend.pipeline.generation.models import IdeaCandidate
    from backend.providers.base import LLMProvider


class ExperimentGenerator:
    """Generates Python experiment code from an ``IdeaCandidate``.

    Parameters
    ----------
    provider:
        Optional ``LLMProvider``.  When supplied the generator will delegate
        to the LLM for richer code; otherwise a deterministic template is used.
    """

    def __init__(self, provider: LLMProvider | None = None) -> None:
        self._provider = provider

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    async def generate(self, idea: IdeaCandidate) -> str:
        """Generate experiment code from *idea*.

        Returns a Python source-code string that is ready for execution
        inside the sandbox.
        """
        if self._provider is not None:
            return await self._generate_with_llm(idea)
        return self._generate_template(idea)

    # ------------------------------------------------------------------
    # Template-based generation (no LLM)
    # ------------------------------------------------------------------

    def _generate_template(self, idea: IdeaCandidate) -> str:
        """Deterministic template generation — no external calls needed."""
        title = _escape(idea.title)
        problem = _escape(idea.problem_statement)
        method = _escape(idea.proposed_method)
        evaluation = _escape(idea.evaluation_approach or "empirical comparison")
        contributions = _escape(idea.expected_contributions or "measurable improvement")

        code = textwrap.dedent(
            f"""\
            #!/usr/bin/env python3
            \"""
            Auto-generated experiment: {title}
            Generated by ExperimentGenerator (BATCH-66/TASK-01)
            \"""

            import json
            import random
            import statistics
            import time

            # ── Hypothesis ────────────────────────────────────────────────
            # Problem statement:
            #   {problem}
            #
            # Proposed method:
            #   {method}
            #
            # Evaluation approach:
            #   {evaluation}
            #
            # Expected contributions:
            #   {contributions}
            # ──────────────────────────────────────────────────────────────


            def generate_synthetic_data(n: int = 200, seed: int = 42) -> list[dict]:
                \"""Create a synthetic dataset for baseline comparison.

                Each record has a feature vector and a target label so that
                simple heuristics can be compared against the proposed method.
                \"""
                rng = random.Random(seed)
                dataset = []
                for i in range(n):
                    feature_a = rng.gauss(0.0, 1.0)
                    feature_b = rng.uniform(-1.0, 1.0)
                    # Ground-truth: label depends on a simple rule
                    label = 1 if (feature_a + feature_b) > 0.2 else 0
                    dataset.append({{
                        "id": i,
                        "feature_a": feature_a,
                        "feature_b": feature_b,
                        "label": label,
                    }})
                return dataset


            def random_baseline_predict(features: list[dict]) -> list[int]:
                \"""Random baseline: flip a coin for each sample.\"""
                rng = random.Random(123)
                return [rng.randint(0, 1) for _ in features]


            def heuristic_baseline_predict(features: list[dict]) -> list[int]:
                \"""Simple heuristic: positive when feature_a > 0.

                This represents the 'proposed method' proxy — a lightweight
                rule that should outperform random guessing.
                \"""
                return [1 if row["feature_a"] > 0 else 0 for row in features]


            def compute_metrics(predictions: list[int], labels: list[int]) -> dict:
                \"""Compute accuracy, precision, recall, F1.\"""
                tp = sum(1 for p, l in zip(predictions, labels) if p == 1 and l == 1)
                fp = sum(1 for p, l in zip(predictions, labels) if p == 1 and l == 0)
                fn = sum(1 for p, l in zip(predictions, labels) if p == 0 and l == 1)
                tn = sum(1 for p, l in zip(predictions, labels) if p == 0 and l == 0)

                accuracy = (tp + tn) / len(labels) if labels else 0.0
                precision = tp / (tp + fp) if (tp + fp) else 0.0
                recall = tp / (tp + fn) if (tp + fn) else 0.0
                f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0

                return {{
                    "accuracy": round(accuracy, 4),
                    "precision": round(precision, 4),
                    "recall": round(recall, 4),
                    "f1": round(f1, 4),
                    "tp": tp, "fp": fp, "fn": fn, "tn": tn,
                }}


            def main() -> None:
                \"""Run the experiment: data generation → baselines → results.\"""
                print("=" * 60)
                print("EXPERIMENT: {_escape_brackets(title)}")
                print("=" * 60)
                print()
                print("HYPOTHESIS: {_escape_brackets(problem)}")
                print()
                print("METHOD: {_escape_brackets(method)}")
                print()

                # 1. Generate synthetic data
                t0 = time.monotonic()
                dataset = generate_synthetic_data(n=200)
                labels = [row["label"] for row in dataset]
                data_time = time.monotonic() - t0
                print(f"[data] Generated {{len(dataset)}} samples in {{data_time:.4f}}s")

                # 2. Run baselines
                # --- random baseline ---
                t0 = time.monotonic()
                random_preds = random_baseline_predict(dataset)
                random_time = time.monotonic() - t0
                random_metrics = compute_metrics(random_preds, labels)

                # --- heuristic baseline (proxy for proposed method) ---
                t0 = time.monotonic()
                heuristic_preds = heuristic_baseline_predict(dataset)
                heuristic_time = time.monotonic() - t0
                heuristic_metrics = compute_metrics(heuristic_preds, labels)

                # 3. Compare results
                print()
                print("BASELINE COMPARISON")
                print("-" * 40)
                print(f"  Random baseline:   accuracy={{random_metrics['accuracy']}}  "
                      f"f1={{random_metrics['f1']}}  time={{random_time:.4f}}s")
                print(f"  Heuristic baseline: accuracy={{heuristic_metrics['accuracy']}}  "
                      f"f1={{heuristic_metrics['f1']}}  time={{heuristic_time:.4f}}s")
                print()

                improvement = heuristic_metrics["accuracy"] - random_metrics["accuracy"]
                print(f"  Improvement over random: {{improvement:+.4f}} accuracy")
                print()

                # 4. JSON output
                results = {{
                    "experiment": "{_escape_brackets(title)}",
                    "hypothesis": "{_escape_brackets(problem)}",
                    "method": "{_escape_brackets(method)}",
                    "n_samples": len(dataset),
                    "baselines": {{
                        "random": random_metrics,
                        "heuristic": heuristic_metrics,
                    }},
                    "improvement_accuracy": round(improvement, 4),
                    "data_generation_time_s": round(data_time, 4),
                    "random_inference_time_s": round(random_time, 4),
                    "heuristic_inference_time_s": round(heuristic_time, 4),
                }}

                print("RESULTS (JSON)")
                print(json.dumps(results, indent=2))


            if __name__ == "__main__":
                main()
            """
        )
        return code

    # ------------------------------------------------------------------
    # LLM-based generation
    # ------------------------------------------------------------------

    async def _generate_with_llm(self, idea: IdeaCandidate) -> str:
        """Delegate code generation to the configured LLM provider."""
        prompt = (
            "Generate a Python experiment script for the following research idea. "
            "Use ONLY standard-library modules (random, statistics, time, json). "
            "The script must:\n"
            "1. Print the hypothesis / problem statement\n"
            "2. Generate synthetic data using random\n"
            "3. Run at least two baselines for comparison\n"
            "4. Compute metrics (accuracy, precision, recall, F1)\n"
            "5. Print results as JSON\n\n"
            f"Title: {idea.title}\n"
            f"Problem: {idea.problem_statement}\n"
            f"Method: {idea.proposed_method}\n"
            f"Evaluation: {idea.evaluation_approach}\n"
        )
        response = await self._provider.complete(
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=4096,
        )
        # Strip markdown fences if present
        code = response.strip()
        if code.startswith("```python"):
            code = code[len("```python"):]
        if code.startswith("```"):
            code = code[3:]
        if code.endswith("```"):
            code = code[:-3]
        return code.strip()


# ======================================================================
# Helpers
# ======================================================================

def _escape(text: str) -> str:
    """Escape triple quotes and backslashes in template values."""
    return text.replace("\\", "\\\\").replace('"""', '\\"""').replace("'''", "\\'\\'\\'")


def _escape_brackets(text: str) -> str:
    """Escape curly braces for .format() safety (used inside f-string template)."""
    return text.replace("{", "{{").replace("}", "}}")
